def _projections(content: str, rich_items: list[dict[str, Any]]) -> dict[str, Any]:
    message = {
        "id": "m-1",
        "role": "assistant",
        "content": content,
        "metadata": {
            "rich_items_version": 1,
            "rich_items": rich_items,
            "rich_reference_warnings": [],
        },
    }
    out: dict[str, Any] = {}
    for name, flags in _CAPABILITIES.items():
        projected = project_ai_sdk_message_for_capability(message, **flags)
        metadata = projected.get("metadata") or {}
        out[name] = {
            "content": projected["content"],
            "rich_items": metadata.get("rich_items"),
        }
    return out


def _stale_transient_case() -> dict[str, Any]:
    widget = {
        "id": "widget:w-draft",
        "type": "live_widget",
        "display_policy": "inline_or_append",
        "payload": {
            "widget_id": "w-draft",
            "session_id": "conv-1",
            "status": "active",
            "version": 1,
            "connection_endpoint": "/widgets/w-draft/connection",
        },
    }
    steps = _example_cases()["edge-google-steps"]["rich_items"][0]
    state = RichStreamState()
    state.append_text(f"Draft with {_marker(widget)}")
    state.apply_rich_items_upsert([widget])
    state.accumulated_text = f"Final:\n\n{_marker(steps)}"
    state.replace_with_finalized([steps])
    view = state.build_view()
    return {
        "example": "Stale transient item after the draft was rewritten",
        "transient_upserts": [widget],
        "final_content": state.accumulated_text,
        "final_rich_items": [steps],
        "expected_registry_ids": sorted(state.items_by_id),
        "expected_segments": [
            {"kind": segment.kind, "text": segment.text} for segment in view.segments
        ],
    }


def _partial_figure_case() -> dict[str, Any]:
    figure = _shadow_figure()
    degraded = degrade_source_figure(figure, [figure["payload"]["items"][0]])
    return {
        "example": "Comparison that lost a cell after composition",
        "original": figure,
        "degraded": degraded,
        "degraded_projections": _projections(
            f"Compare the shadows:\n\n{_marker(degraded)}", [degraded]
        ),
    }


def _all_fixtures() -> dict[str, dict[str, Any]]:
    fixtures: dict[str, dict[str, Any]] = {}
    for name, case in _example_cases().items():
        fixtures[name] = {
            **case,
            "projections": _projections(case["content"], case["rich_items"]),
        }
    fixtures["stale-transient-after-draft-replacement"] = _stale_transient_case()
    fixtures["partial-figure-failure"] = _partial_figure_case()
    return fixtures


def _render(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


@pytest.mark.parametrize("name", sorted(_all_fixtures()))
def test_fixture_matches_the_backend_contract(name):
    expected = _render(_all_fixtures()[name])
    path = FIXTURE_DIR / f"{name}.json"
    if _WRITE:
        FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8", newline="\n")
    assert path.read_text(encoding="utf-8") == expected


def test_every_supplied_example_has_a_fixture():
    examples = {case["example"] for case in _all_fixtures().values()}
    assert {
        "Edge/Google sequence",
        "Game edition comparison",
        "Clock/voltage/FPS comparison",
        "Tweak assessment table",
        "Side-by-side graphics screenshots",
    } <= examples


def test_fallback_markdown_agrees_with_component_values():
    """Tables, labels, and fallback text must agree on values and verdicts."""
    for case in _example_cases().values():
        for item in case["rich_items"]:
            payload = item["payload"]
            fallback = payload.get("fallback_markdown")
            if fallback is None:
                continue  # a plain selected image has no text form
            for bar in payload.get("bars") or ():
                value = bar["value"]
                shown = str(int(value)) if float(value).is_integer() else format(value, ".15g")
                assert f"| {shown} |" in fallback
            for row in payload.get("rows") or ():
                if row.get("assessment"):
                    assert row["assessment"]["label"] in fallback


def test_synthetic_bars_cannot_be_mistaken_for_a_benchmark():
    fps = _example_cases()["overclock-bars"]["rich_items"][2]["payload"]

    assert fps["basis"] == "calculated"
    assert "scales exactly with core clock" in fps["fallback_markdown"]
    assert fps["scale"] == {"min": 0, "max": 101}
