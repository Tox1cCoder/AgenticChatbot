"""Shared contract fixtures for answer visuals and source figures.

Each JSON file under ``tests/fixtures/rich_answer_visuals/`` is what the
backend produces for one supplied example: the public rich items, the stored
answer, and that answer projected for each capability combination. The
external frontend renders the same files.

The files are generated by the real builders. Set
``RICH_ANSWER_VISUAL_FIXTURES_WRITE=1`` to rewrite them after an intended
contract change; otherwise a difference fails the test.
"""

